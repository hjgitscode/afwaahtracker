import { ArrowRight, GitCompareArrows, TriangleAlert } from 'lucide-react';
import Card, { CardHeader } from '../ui/Card.jsx';
import { EmptyState } from '../ui/States.jsx';
import { formatDate, truncate } from '../../utils/format.js';

const COMPONENT_LABEL = {
  ACTOR: 'Actor', ACTION: 'Action', TARGET: 'Target', LOCATION: 'Location', EVENT: 'Event',
  DATE: 'Date', QUANTITY: 'Quantity', CERTAINTY: 'Certainty', ATTRIBUTION: 'Attribution',
};

/** Groups ledger rows by parent -> child transition. */
function groupTransitions(rows) {
  const map = new Map();
  rows.forEach((r) => {
    const key = `${r.parent_variant_id}-${r.child_variant_id}`;
    if (!map.has(key)) map.set(key, { ...r, changes: [] });
    map.get(key).changes.push(r);
  });
  return [...map.values()];
}

export default function MutationLedger({ mutations }) {
  const transitions = groupTransitions(mutations || []);
  const escalations = (mutations || []).filter((m) => m.is_escalation === 'Y').length;
  return (
    <Card>
      <CardHeader
        label="Generated by PL/SQL · GENERATE_MUTATION_LEDGER"
        title="Mutation ledger"
        subtitle="What changed as this claim travelled?"
        icon={GitCompareArrows}
      />
      {!transitions.length ? (
        <EmptyState compact icon={GitCompareArrows} title="No mutations recorded">
          No parent–child variants with structured differences are known for this claim yet.
        </EmptyState>
      ) : (
        <>
          <div className="mb-5 flex flex-wrap gap-x-6 gap-y-1 text-[14px] text-ink-2">
            <span><b className="text-ink">{mutations.length}</b> component changes</span>
            <span><b className="text-ink">{transitions.length}</b> transitions</span>
            {escalations > 0 && (
              <span className="inline-flex items-center gap-1.5"><TriangleAlert size={15} className="text-warning" /><b className="text-ink">{escalations}</b> strong certainty escalation{escalations > 1 ? 's' : ''}</span>
            )}
          </div>
          <ol className="space-y-4">
            {transitions.map((t) => (
              <li key={`${t.parent_variant_id}-${t.child_variant_id}`} className="rounded-xl border border-line bg-white p-4 md:p-5">
                <div className="grid gap-3 md:grid-cols-[1fr_auto_1fr] md:items-start">
                  <div className="min-w-0">
                    <div className="meta-label">From source</div>
                    <div className="mt-0.5 font-bold text-ink">{t.from_publisher}</div>
                    <div className="text-[13px] text-muted">{t.from_platform} · {formatDate(t.from_published)}</div>
                    <div className="mt-1 text-[14px] text-ink-2">“{truncate(t.from_text, 90)}”</div>
                  </div>
                  <ArrowRight className="hidden self-center text-muted md:block" size={20} />
                  <div className="min-w-0">
                    <div className="meta-label">To source</div>
                    <div className="mt-0.5 font-bold text-ink">{t.to_publisher}</div>
                    <div className="text-[13px] text-muted">{t.to_platform} · {formatDate(t.to_published)}</div>
                    <div className="mt-1 text-[14px] text-ink-2">“{truncate(t.to_text, 90)}”</div>
                  </div>
                </div>
                <div className="mt-4 overflow-x-auto">
                  <table className="w-full min-w-[460px] text-[14.5px]">
                    <thead>
                      <tr className="text-left">
                        <th className="meta-label w-[150px] pb-2">Component</th>
                        <th className="meta-label pb-2">Old value</th>
                        <th className="w-8 pb-2" />
                        <th className="meta-label pb-2">New value</th>
                      </tr>
                    </thead>
                    <tbody>
                      {t.changes.map((c) => (
                        <tr key={c.mutation_id} className="border-t border-line">
                          <td className="py-2.5 pr-3">
                            <span className="inline-flex items-center gap-1.5 text-[12px] font-extrabold uppercase tracking-[0.07em] text-deep">
                              {COMPONENT_LABEL[c.changed_component] || c.changed_component}
                              {c.is_escalation === 'Y' && (
                                <span title="Strong certainty escalation" className="inline-block h-2.5 w-2.5 rounded-full bg-amber ring-2 ring-[#fdf3d6]" />
                              )}
                            </span>
                          </td>
                          <td className="py-2.5 pr-3 text-muted">{c.old_value ?? <span className="italic">NULL</span>}</td>
                          <td className="py-2.5 text-muted"><ArrowRight size={14} /></td>
                          <td className={`py-2.5 font-bold ${c.is_escalation === 'Y' ? 'text-[#a8761a]' : 'text-primary'}`}>
                            {c.new_value ?? <span className="font-normal italic text-muted">NULL</span>}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </li>
            ))}
          </ol>
        </>
      )}
    </Card>
  );
}
