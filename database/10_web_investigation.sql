--------------------------------------------------------------------------------
-- Duplicate lookup: same URL, same canonical URL, or same platform + external id.
-- Returns NULL when the item is not stored yet.
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION find_source_id (
    p_url           IN VARCHAR2,
    p_canonical_url IN VARCHAR2 DEFAULT NULL,
    p_platform_id   IN NUMBER   DEFAULT NULL,
    p_external_id   IN VARCHAR2 DEFAULT NULL
) RETURN NUMBER
IS
    v_id NUMBER;
BEGIN
    SELECT MIN(source_id) INTO v_id
      FROM sources
     WHERE source_url = p_url
        OR (p_canonical_url IS NOT NULL
            AND (source_url = p_canonical_url OR canonical_url = p_canonical_url))
        OR canonical_url = p_url
        OR (p_external_id IS NOT NULL
            AND platform_id = p_platform_id
            AND external_source_id = p_external_id);
    RETURN v_id;
END find_source_id;
/

--------------------------------------------------------------------------------
-- Deduplicated insert used by feeds (origin AUTOMATED) and live web search
-- (origin WEB_SEARCH). Returns the new SOURCE_ID, or 0 when already stored.
-- An unknown publication date stays NULL.
-- A submitted link (e.g. a Hacker News post linking an article) that points to
-- a stored source is recorded as a SUBMITTED_LINK reference and as source
-- dependence, because the link itself is the evidence.
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION ingest_source (
    p_platform_id         IN NUMBER,
    p_ingestion_source_id IN NUMBER,
    p_publisher           IN VARCHAR2,
    p_author              IN VARCHAR2,
    p_title               IN VARCHAR2,
    p_url                 IN VARCHAR2,
    p_linked_url          IN VARCHAR2,
    p_external_id         IN VARCHAR2,
    p_published_at        IN TIMESTAMP,
    p_snippet             IN VARCHAR2,
    p_engagement          IN NUMBER,
    p_origin              IN VARCHAR2 DEFAULT 'AUTOMATED',
    p_canonical_url       IN VARCHAR2 DEFAULT NULL
) RETURN NUMBER
IS
    v_parent_id   NUMBER;
    v_new_id      NUMBER;
BEGIN
    IF find_source_id(p_url, p_canonical_url, p_platform_id, p_external_id) IS NOT NULL THEN
        RETURN 0;
    END IF;

    IF p_linked_url IS NOT NULL AND p_linked_url <> p_url THEN
        v_parent_id := find_source_id(p_linked_url);
    END IF;

    INSERT INTO sources
        (platform_id, ingestion_source_id, publisher, author, source_title,
         source_url, canonical_url, linked_url, external_source_id, published_at,
         snippet, engagement_count, source_status, origin_type,
         derived_from_source_id, provenance_note)
    VALUES
        (p_platform_id, p_ingestion_source_id, SUBSTR(p_publisher, 1, 200),
         SUBSTR(p_author, 1, 200), SUBSTR(p_title, 1, 1000), p_url,
         CASE WHEN p_canonical_url <> p_url THEN SUBSTR(p_canonical_url, 1, 1000) END,
         p_linked_url, p_external_id, p_published_at,
         SUBSTR(p_snippet, 1, 4000), GREATEST(NVL(p_engagement, 0), 0),
         'ACTIVE', NVL(p_origin, 'AUTOMATED'), v_parent_id,
         CASE WHEN v_parent_id IS NOT NULL
              THEN 'Submitted link points to stored source #' || v_parent_id
                   || ' (deterministic URL match).'
              WHEN p_origin = 'WEB_SEARCH'
              THEN 'Retrieved by live web search. No known upstream source yet.'
              ELSE 'Automatically ingested. No deterministic upstream source known.'
         END)
    RETURNING source_id INTO v_new_id;

    IF v_parent_id IS NOT NULL THEN
        INSERT INTO source_references (from_source_id, to_source_id, reference_type, confidence_basis)
        VALUES (v_new_id, v_parent_id, 'SUBMITTED_LINK', 'Submitted link equals the stored source URL.');
    END IF;

    RETURN v_new_id;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RETURN 0;
END ingest_source;
/

CREATE OR REPLACE FUNCTION start_web_search_run (
    p_query    IN VARCHAR2,
    p_provider IN VARCHAR2 DEFAULT 'TAVILY'
) RETURN NUMBER
IS
    v_id NUMBER;
BEGIN
    INSERT INTO web_search_runs (query_text, search_provider, status)
    VALUES (SUBSTR(TRIM(p_query), 1, 400), NVL(p_provider, 'TAVILY'), 'RUNNING')
    RETURNING search_run_id INTO v_id;
    RETURN v_id;
END start_web_search_run;
/

CREATE OR REPLACE PROCEDURE finish_web_search_run (
    p_run_id      IN NUMBER,
    p_received    IN NUMBER,
    p_fetched     IN NUMBER,
    p_failed      IN NUMBER,
    p_inserted    IN NUMBER,
    p_duplicates  IN NUMBER,
    p_matched     IN NUMBER,
    p_created     IN NUMBER,
    p_status      IN VARCHAR2,
    p_error       IN VARCHAR2 DEFAULT NULL
)
IS
BEGIN
    UPDATE web_search_runs
       SET completed_at       = SYSTIMESTAMP,
           results_received   = NVL(p_received, 0),
           pages_fetched      = NVL(p_fetched, 0),
           pages_failed       = NVL(p_failed, 0),
           sources_inserted   = NVL(p_inserted, 0),
           duplicates_skipped = NVL(p_duplicates, 0),
           claims_matched     = NVL(p_matched, 0),
           claims_created     = NVL(p_created, 0),
           status             = p_status,
           error_message      = SUBSTR(p_error, 1, 1000)
     WHERE search_run_id = p_run_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20040, 'Web search run ' || p_run_id || ' not found.');
    END IF;
END finish_web_search_run;
