CREATE OR REPLACE VIEW vw_web_search_runs AS
SELECT r.search_run_id,
       r.query_text,
       r.search_provider,
       r.started_at,
       r.completed_at,
       ROUND((CAST(NVL(r.completed_at, SYSTIMESTAMP) AS DATE) - CAST(r.started_at AS DATE)) * 86400) AS duration_seconds,
       r.results_received,
       r.pages_fetched,
       r.pages_failed,
       r.sources_inserted,
       r.duplicates_skipped,
       r.claims_matched,
       r.claims_created,
       r.status,
       r.error_message,
       (SELECT COUNT(*) FROM search_result_links l WHERE l.search_run_id = r.search_run_id) AS linked_sources,
       (SELECT COUNT(DISTINCT v.claim_id)
          FROM search_result_links l
          JOIN claim_variants v ON v.source_id = l.source_id
         WHERE l.search_run_id = r.search_run_id)                                          AS claim_families
  FROM web_search_runs r;

CREATE OR REPLACE VIEW vw_source_references AS
SELECT r.reference_id,
       r.reference_type,
       r.detected_at,
       r.confidence_basis,
       f.source_id     AS from_source_id,
       f.publisher     AS from_publisher,
       f.source_title  AS from_title,
       f.source_url    AS from_url,
       f.published_at  AS from_published_at,
       t.source_id     AS to_source_id,
       t.publisher     AS to_publisher,
       t.source_title  AS to_title,
       t.source_url    AS to_url,
       t.published_at  AS to_published_at,
       CASE WHEN f.derived_from_source_id = t.source_id THEN 'Y' ELSE 'N' END AS sets_dependence
  FROM source_references r
  JOIN sources f ON f.source_id = r.from_source_id
  JOIN sources t ON t.source_id = r.to_source_id;

