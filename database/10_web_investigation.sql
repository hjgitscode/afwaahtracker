CREATE OR REPLACE PROCEDURE record_search_result_link (
    p_run_id     IN NUMBER,
    p_source_id  IN NUMBER,
    p_rank       IN NUMBER,
    p_provider   IN VARCHAR2,
    p_snippet    IN VARCHAR2,
    p_duplicate  IN CHAR DEFAULT 'N'
)
IS
BEGIN
    MERGE INTO search_result_links l
    USING (SELECT p_run_id AS search_run_id, p_source_id AS source_id FROM dual) src
       ON (l.search_run_id = src.search_run_id AND l.source_id = src.source_id)
     WHEN MATCHED THEN
          UPDATE SET l.search_rank = LEAST(l.search_rank, p_rank)
     WHEN NOT MATCHED THEN
          INSERT (search_run_id, source_id, search_rank, search_provider, result_snippet, was_duplicate)
          VALUES (p_run_id, p_source_id, GREATEST(NVL(p_rank, 1), 1), NVL(p_provider, 'TAVILY'),
                  SUBSTR(p_snippet, 1, 1000), NVL(p_duplicate, 'N'));
END record_search_result_link;
/

-- Records explicit evidence that FROM points at TO. Returns 1 if a new row was added.
CREATE OR REPLACE FUNCTION record_source_reference (
    p_from_source_id IN NUMBER,
    p_to_source_id   IN NUMBER,
    p_type           IN VARCHAR2,
    p_basis          IN VARCHAR2
) RETURN NUMBER
IS
BEGIN
    IF p_from_source_id IS NULL OR p_to_source_id IS NULL
       OR p_from_source_id = p_to_source_id THEN
        RETURN 0;
    END IF;

    MERGE INTO source_references r
    USING (SELECT p_from_source_id AS f, p_to_source_id AS t, p_type AS ty FROM dual) src
       ON (r.from_source_id = src.f AND r.to_source_id = src.t AND r.reference_type = src.ty)
     WHEN NOT MATCHED THEN
          INSERT (from_source_id, to_source_id, reference_type, confidence_basis)
          VALUES (src.f, src.t, src.ty, SUBSTR(p_basis, 1, 400));
    RETURN SQL%ROWCOUNT;
END record_source_reference;
/

--------------------------------------------------------------------------------
-- WORDING_SIMILARITY (0..100): deterministic lexical similarity of two
-- wordings = 70 % word-overlap coefficient (words of 3+ letters, minus a
-- small stop-word list) + 30 % Jaro-Winkler (UTL_MATCH). No AI, no embeddings.
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION wording_similarity (p_a IN VARCHAR2, p_b IN VARCHAR2)
RETURN NUMBER
IS
    TYPE t_set IS TABLE OF PLS_INTEGER INDEX BY VARCHAR2(60);
    v_a      t_set;
    v_b      t_set;
    v_word   VARCHAR2(60);
    v_common PLS_INTEGER := 0;
    v_key    VARCHAR2(60);
    v_stop   CONSTANT VARCHAR2(400) :=
        ' the and for with from that this was were are has have had will would could '
        || 'into over after about says said than then they their them its his her you your '
        || 'not but all new more also who what when where how why which been being ';

    PROCEDURE tokenise (p_text IN VARCHAR2, p_set IN OUT NOCOPY t_set) IS
        i PLS_INTEGER := 1;
    BEGIN
        LOOP
            v_word := SUBSTR(REGEXP_SUBSTR(LOWER(p_text), '[a-z0-9]{3,}', 1, i), 1, 60);
            EXIT WHEN v_word IS NULL OR i > 200;
            IF INSTR(v_stop, ' ' || v_word || ' ') = 0 THEN
                p_set(v_word) := 1;
            END IF;
            i := i + 1;
        END LOOP;
    END tokenise;
BEGIN
    IF p_a IS NULL OR p_b IS NULL THEN
        RETURN 0;
    END IF;
    tokenise(p_a, v_a);
    tokenise(p_b, v_b);
    IF v_a.COUNT = 0 OR v_b.COUNT = 0 THEN
        RETURN ROUND(0.3 * UTL_MATCH.JARO_WINKLER_SIMILARITY(LOWER(p_a), LOWER(p_b)), 1);
    END IF;

    v_key := v_a.FIRST;
    WHILE v_key IS NOT NULL LOOP
        IF v_b.EXISTS(v_key) THEN
            v_common := v_common + 1;
        END IF;
        v_key := v_a.NEXT(v_key);
    END LOOP;

    RETURN ROUND(70 * v_common / LEAST(v_a.COUNT, v_b.COUNT)
                 + 0.3 * UTL_MATCH.JARO_WINKLER_SIMILARITY(LOWER(SUBSTR(p_a, 1, 400)),
                                                          LOWER(SUBSTR(p_b, 1, 400))), 1);
END wording_similarity;
/

--------------------------------------------------------------------------------
-- CHOOSE_VARIANT_PARENT
-- Picks the wording parent for a source's variant inside one claim family:
--   1. EXPLICIT_REFERENCE   the source references (hyperlink, submitted link,
--                           manual) another source that already has a variant
--                           in this claim -> that variant.
--   2. LEXICAL_PREDECESSOR  otherwise the most similar variant whose source was
--                           published EARLIER (both dates known) and whose
--                           similarity is at least p_min_similarity (55).
--   3. NONE                 otherwise no parent. The earliest variant is never
--                           chosen merely because it is the earliest.
-- p_exclude_variant_id lets RELINK_CLAIM_LINEAGE skip the variant itself and
-- its descendants (prevents cycles).
--------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE choose_variant_parent (
    p_claim_id           IN  NUMBER,
    p_source_id          IN  NUMBER,
    p_variant_text       IN  VARCHAR2,
    p_exclude_variant_id IN  NUMBER DEFAULT NULL,
    p_min_similarity     IN  NUMBER DEFAULT 55,
    o_parent_variant_id  OUT NUMBER,
    o_basis              OUT VARCHAR2,
    o_similarity         OUT NUMBER
)
IS
    v_published TIMESTAMP;
BEGIN
    o_parent_variant_id := NULL;
    o_basis := 'NONE';
    o_similarity := NULL;

    SELECT published_at INTO v_published FROM sources WHERE source_id = p_source_id;

    -- 1. Explicit reference to a source already in this claim family
    FOR r IN (SELECT v.variant_id
                FROM (SELECT to_source_id FROM source_references WHERE from_source_id = p_source_id
                      UNION
                      SELECT derived_from_source_id FROM sources
                       WHERE source_id = p_source_id AND derived_from_source_id IS NOT NULL) rf
                JOIN claim_variants v ON v.source_id = rf.to_source_id AND v.claim_id = p_claim_id
                JOIN sources s        ON s.source_id = v.source_id
               WHERE (p_exclude_variant_id IS NULL
                      OR v.variant_id NOT IN (SELECT variant_id FROM claim_variants
                                               START WITH variant_id = p_exclude_variant_id
                                               CONNECT BY NOCYCLE PRIOR variant_id = parent_variant_id))
               ORDER BY s.published_at NULLS LAST, v.variant_id
               FETCH FIRST 1 ROWS ONLY)
    LOOP
        o_parent_variant_id := r.variant_id;
        o_basis := 'EXPLICIT_REFERENCE';
        RETURN;
    END LOOP;

    -- 2. Most similar strictly earlier variant (ties -> the closest in time)
    IF v_published IS NULL THEN
        RETURN;
    END IF;

    FOR r IN (SELECT variant_id, sim
                FROM (SELECT v.variant_id,
                             wording_similarity(v.variant_text, p_variant_text) AS sim,
                             s.published_at
                        FROM claim_variants v
                        JOIN sources s ON s.source_id = v.source_id
                       WHERE v.claim_id = p_claim_id
                         AND v.source_id <> p_source_id
                         AND s.published_at < v_published
                         AND (p_exclude_variant_id IS NULL
                              OR v.variant_id NOT IN (SELECT variant_id FROM claim_variants
                                                       START WITH variant_id = p_exclude_variant_id
                                                       CONNECT BY NOCYCLE PRIOR variant_id = parent_variant_id)))
               WHERE sim >= p_min_similarity
               ORDER BY sim DESC, published_at DESC, variant_id DESC
               FETCH FIRST 1 ROWS ONLY)
    LOOP
        o_parent_variant_id := r.variant_id;
        o_basis := 'LEXICAL_PREDECESSOR';
        o_similarity := r.sim;
    END LOOP;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
END choose_variant_parent;
/

--------------------------------------------------------------------------------
-- APPLY_SOURCE_DEPENDENCE
-- After a source joins a claim family, record its known upstream source when
-- (and only when) it explicitly references a stored source in the same claim.
-- The earliest-published referenced source wins; cycles are refused.
-- Returns the upstream SOURCE_ID that was set, or NULL.
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION apply_source_dependence (p_source_id IN NUMBER)
RETURN NUMBER
IS
    v_current NUMBER;
    v_cycle   NUMBER;
BEGIN
    SELECT derived_from_source_id INTO v_current FROM sources WHERE source_id = p_source_id;
    IF v_current IS NOT NULL THEN
        RETURN NULL;
    END IF;

    FOR r IN (SELECT t.source_id, sr.reference_type
                FROM source_references sr
                JOIN sources t ON t.source_id = sr.to_source_id
               WHERE sr.from_source_id = p_source_id
                 AND EXISTS (SELECT 1
                               FROM claim_variants a
                               JOIN claim_variants b ON b.claim_id = a.claim_id
                              WHERE a.source_id = p_source_id
                                AND b.source_id = t.source_id)
               ORDER BY t.published_at NULLS LAST, t.source_id)
    LOOP
        -- refuse if the target already (transitively) derives from this source
        SELECT COUNT(*) INTO v_cycle
          FROM sources
         WHERE source_id = p_source_id
         START WITH source_id = r.source_id
         CONNECT BY NOCYCLE PRIOR derived_from_source_id = source_id;

        IF v_cycle = 0 THEN
            UPDATE sources
               SET derived_from_source_id = r.source_id,
                   provenance_note = SUBSTR('Known derived: explicit ' || LOWER(REPLACE(r.reference_type, '_', ' '))
                                     || ' to stored source #' || r.source_id || ' in the same claim family.', 1, 500)
             WHERE source_id = p_source_id;
            RETURN r.source_id;
        END IF;
    END LOOP;
    RETURN NULL;
END apply_source_dependence;
/

--------------------------------------------------------------------------------
-- RELINK_CLAIM_LINEAGE
-- Recomputes the parent of every automatically linked variant of one claim
-- (bases AUTO_ROOT, EXPLICIT_REFERENCE, LEXICAL_PREDECESSOR, NONE) in
-- publication order. Curated / manual lineage is never touched. The compound
-- trigger on CLAIM_VARIANTS regenerates the Mutation Ledger for every change.
--------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE relink_claim_lineage (p_claim_id IN NUMBER)
IS
    v_parent NUMBER;
    v_basis  VARCHAR2(20);
    v_sim    NUMBER;
BEGIN
    FOR v IN (SELECT cv.variant_id, cv.source_id, cv.variant_text,
                     cv.parent_variant_id, cv.lineage_basis
                FROM claim_variants cv
                JOIN sources s ON s.source_id = cv.source_id
               WHERE cv.claim_id = p_claim_id
                 AND cv.lineage_basis IN ('AUTO_ROOT','EXPLICIT_REFERENCE','LEXICAL_PREDECESSOR','NONE')
               ORDER BY s.published_at NULLS LAST, cv.variant_id)
    LOOP
        choose_variant_parent(p_claim_id, v.source_id, v.variant_text, v.variant_id, 55,
                              v_parent, v_basis, v_sim);
        IF NVL(v_parent, -1) <> NVL(v.parent_variant_id, -1) OR v_basis <> v.lineage_basis THEN
            UPDATE claim_variants
               SET parent_variant_id = v_parent,
                   lineage_basis     = v_basis
             WHERE variant_id = v.variant_id;
        END IF;
    END LOOP;
END relink_claim_lineage;
/

-- Existing databases: replace the old "everything hangs off the earliest
-- variant" links with evidence-based lineage. A no-op on a fresh install.
BEGIN
    FOR c IN (SELECT DISTINCT claim_id FROM claim_variants WHERE lineage_basis = 'AUTO_ROOT') LOOP
        relink_claim_lineage(c.claim_id);
    END LOOP;
    COMMIT;
END;
