-- Helper: run DDL and ignore errors that mean "this step was already applied".
CREATE OR REPLACE PROCEDURE afw_ddl (p_sql IN VARCHAR2)
AUTHID CURRENT_USER   -- runs with the caller's roles, so role-granted CREATE TABLE works
IS
BEGIN
    EXECUTE IMMEDIATE p_sql;
EXCEPTION
    WHEN OTHERS THEN
        -- -955 name in use, -1430 column exists, -1442/-1451 nullability already
        -- set, -2260/-2261/-2264/-2275 constraint exists, -1408 index exists,
        -- -2443 constraint does not exist
        IF SQLCODE NOT IN (-955, -1430, -1442, -1451, -2260, -2261, -2264, -2275, -1408, -2443) THEN
            RAISE;
        END IF;
END afw_ddl;
/

-- Helper: replace a CHECK constraint only when it does not yet allow p_needed.
-- Later migrations widen these lists; re-running an earlier migration must
-- never narrow them again.
CREATE OR REPLACE PROCEDURE afw_swap_check (
    p_table      IN VARCHAR2,
    p_constraint IN VARCHAR2,
    p_needed     IN VARCHAR2,
    p_condition  IN VARCHAR2
)
AUTHID CURRENT_USER
IS
    v_found NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_found
      FROM user_constraints
     WHERE constraint_name = UPPER(p_constraint)
       AND table_name = UPPER(p_table)
       AND INSTR(search_condition_vc, '''' || p_needed || '''') > 0;
    IF v_found = 0 THEN
        afw_ddl('ALTER TABLE ' || p_table || ' DROP CONSTRAINT ' || p_constraint);
        afw_ddl('ALTER TABLE ' || p_table || ' ADD CONSTRAINT ' || p_constraint || ' CHECK (' || p_condition || ')');
    END IF;
END afw_swap_check;
