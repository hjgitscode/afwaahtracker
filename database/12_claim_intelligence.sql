-- One row per claim family with every metric the claim page shows.
-- known_echo_ratio = sources with a known upstream source / all sources x 100
CREATE OR REPLACE VIEW vw_claim_investigation AS
SELECT c.claim_id,
       c.canonical_claim,
       c.status,
       c.claim_origin,
       p.claim_type,
       p.subject_text                                              AS subject,
       p.predicate_code                                            AS predicate,
       p.object_text                                               AS object,
       p.qualifier_text                                            AS qualifier,
       p.temporal_scope,
       p.normalized_signature,
       MIN(s.published_at)                                         AS first_seen,
       MAX(s.published_at)                                         AS latest_seen,
       COUNT(DISTINCT s.source_id)                                 AS source_count,
       COUNT(DISTINCT s.platform_id)                               AS platform_count,
       COUNT(DISTINCT v.variant_id)                                AS variant_count,
       COUNT(DISTINCT CASE WHEN s.derived_from_source_id IS NOT NULL THEN s.source_id END) AS known_upstream_count,
       CASE WHEN COUNT(DISTINCT s.source_id) = 0 THEN 0
            ELSE ROUND(COUNT(DISTINCT CASE WHEN s.derived_from_source_id IS NOT NULL THEN s.source_id END)
                       / COUNT(DISTINCT s.source_id) * 100, 1) END AS known_echo_ratio,
       COUNT(DISTINCT v.evidence_id)                               AS evidence_count,
       (SELECT COUNT(*) FROM claim_mutations m WHERE m.claim_id = c.claim_id) AS mutation_count
  FROM claims c
  LEFT JOIN claim_propositions p ON p.claim_id = c.claim_id
  LEFT JOIN claim_variants v     ON v.claim_id = c.claim_id
  LEFT JOIN sources s            ON s.source_id = v.source_id
 GROUP BY c.claim_id, c.canonical_claim, c.status, c.claim_origin, p.claim_type, p.subject_text,
          p.predicate_code, p.object_text, p.qualifier_text, p.temporal_scope, p.normalized_signature;

-- One row per variant: the exact evidence sentence and where it came from.
CREATE OR REPLACE VIEW vw_claim_evidence AS
SELECT c.claim_id,
       c.canonical_claim,
       v.variant_id,
       v.parent_variant_id,
       v.lineage_basis,
       v.match_method,
       v.match_score,
       v.certainty,
       v.relation_subject,
       v.relation_predicate,
       v.relation_object,
       v.relation_qualifier,
       v.extraction_basis,
       e.evidence_id,
       NVL(e.sentence_text, v.variant_text)  AS evidence_text,
       e.evidence_type,
       e.extraction_method,
       e.relevance_score,
       s.source_id,
       s.publisher,
       s.source_title,
       s.source_url,
       s.published_at,
       s.origin_type,
       s.derived_from_source_id,
       up.publisher                          AS derived_from_publisher,
       CASE WHEN s.derived_from_source_id IS NULL THEN 'NO_KNOWN_UPSTREAM' ELSE 'KNOWN_DERIVED' END AS dependency,
       p.platform_name
  FROM claims c
  JOIN claim_variants v       ON v.claim_id = c.claim_id
  JOIN sources s              ON s.source_id = v.source_id
  JOIN platforms p            ON p.platform_id = s.platform_id
  LEFT JOIN source_evidence e ON e.evidence_id = v.evidence_id
  LEFT JOIN sources up        ON up.source_id = s.derived_from_source_id;

