-- Deduplicated evidence sentence (MERGE on source + sentence hash)
CREATE OR REPLACE FUNCTION record_evidence (
    p_source_id IN NUMBER,
    p_run_id    IN NUMBER,
    p_text      IN VARCHAR2,
    p_order     IN NUMBER,
    p_score     IN NUMBER,
    p_type      IN VARCHAR2,
    p_method    IN VARCHAR2
) RETURN NUMBER
IS
    v_text VARCHAR2(1000) := TRIM(SUBSTR(p_text, 1, 1000));
    v_hash VARCHAR2(64);
    v_id   NUMBER;
BEGIN
    -- STANDARD_HASH is a SQL function, so it is evaluated through DUAL
    SELECT RAWTOHEX(STANDARD_HASH(LOWER(REGEXP_REPLACE(v_text, '\s+', ' ')), 'SHA256'))
      INTO v_hash FROM dual;
    MERGE INTO source_evidence e
    USING (SELECT p_source_id AS source_id, v_hash AS sentence_hash FROM dual) src
       ON (e.source_id = src.source_id AND e.sentence_hash = src.sentence_hash)
     WHEN MATCHED THEN
          UPDATE SET e.relevance_score = GREATEST(e.relevance_score, NVL(p_score, 0)),
                     e.search_run_id   = NVL(e.search_run_id, p_run_id)
     WHEN NOT MATCHED THEN
          INSERT (source_id, search_run_id, sentence_text, sentence_hash, sentence_order,
                  relevance_score, evidence_type, extraction_method)
          VALUES (p_source_id, p_run_id, v_text, v_hash, NVL(p_order, 0),
                  LEAST(GREATEST(NVL(p_score, 0), 0), 100), p_type, p_method);

    SELECT evidence_id INTO v_id FROM source_evidence
     WHERE source_id = p_source_id AND sentence_hash = v_hash;
    RETURN v_id;
END record_evidence;
