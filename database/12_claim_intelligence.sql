--------------------------------------------------------------------------------
-- CREATE_PROPOSITION_CLAIM: a new claim family from a structured proposition
-- (CLAIMS + FINGERPRINTS + CLAIM_PROPOSITIONS in one SAVEPOINT). If another
-- session created the same signature first, that claim is returned instead.
--------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE create_proposition_claim (
    p_canonical      IN  VARCHAR2,
    p_category_id    IN  NUMBER,
    p_claim_type     IN  VARCHAR2,
    p_subject_id     IN  NUMBER,
    p_subject_text   IN  VARCHAR2,
    p_subject_key    IN  VARCHAR2,
    p_predicate      IN  VARCHAR2,
    p_object_id      IN  NUMBER,
    p_object_text    IN  VARCHAR2,
    p_object_key     IN  VARCHAR2,
    p_qualifier_id   IN  NUMBER,
    p_qualifier_text IN  VARCHAR2,
    p_qualifier_key  IN  VARCHAR2,
    p_temporal       IN  VARCHAR2,
    p_signature      IN  VARCHAR2,
    p_origin_label   IN  VARCHAR2,
    o_claim_id       OUT NUMBER,
    o_created        OUT NUMBER
)
IS
BEGIN
    SELECT MIN(claim_id) INTO o_claim_id FROM claim_propositions WHERE normalized_signature = p_signature;
    IF o_claim_id IS NOT NULL THEN
        o_created := 0;
        RETURN;
    END IF;

    SAVEPOINT before_proposition_claim;
    INSERT INTO claims (canonical_claim, category_id, status, claim_origin, summary)
    VALUES (SUBSTR(p_canonical, 1, 500), p_category_id, 'CANDIDATE', 'AUTOMATED',
            SUBSTR('Claim family built from a structured proposition extracted from ' || p_origin_label || '.', 1, 1000))
    RETURNING claim_id INTO o_claim_id;

    INSERT INTO fingerprints (claim_id, core_assertion, source_pattern, notes, is_curated)
    VALUES (o_claim_id, SUBSTR(p_canonical, 1, 500), SUBSTR('First evidence from ' || p_origin_label, 1, 200),
            'Structured proposition: ' || SUBSTR(p_signature, 1, 300), 'N');

    INSERT INTO claim_propositions
        (claim_id, claim_type, subject_entity_id, subject_text, subject_key, predicate_code,
         object_entity_id, object_text, object_key, qualifier_entity_id, qualifier_text, qualifier_key,
         temporal_scope, normalized_signature, proposition_origin)
    VALUES
        (o_claim_id, p_claim_type, p_subject_id, SUBSTR(p_subject_text, 1, 200), p_subject_key, p_predicate,
         p_object_id, SUBSTR(p_object_text, 1, 200), p_object_key, p_qualifier_id, SUBSTR(p_qualifier_text, 1, 200),
         p_qualifier_key, p_temporal, p_signature, 'EXTRACTED');
    o_created := 1;
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO before_proposition_claim;
        SELECT MIN(claim_id) INTO o_claim_id FROM claim_propositions WHERE normalized_signature = p_signature;
        o_created := 0;
END create_proposition_claim;
