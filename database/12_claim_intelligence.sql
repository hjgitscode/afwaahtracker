-- RESOLVE_ENTITY: find an entity by any alias (name_key match), optionally
-- by acronym for organisations, or create it with its alias. Different
-- punctuation/honorifics never create a second entity.
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION resolve_entity (
    p_text     IN VARCHAR2,
    p_type     IN VARCHAR2,
    p_create   IN CHAR     DEFAULT 'Y',
    p_acronym  IN VARCHAR2 DEFAULT NULL
) RETURN NUMBER
IS
    v_key  VARCHAR2(200) := name_key(p_text);
    v_id   NUMBER;
    v_text VARCHAR2(200) := TRIM(SUBSTR(p_text, 1, 200));
BEGIN
    IF v_key IS NULL OR LENGTH(v_key) < 2 THEN
        RETURN NULL;
    END IF;

    SELECT MIN(entity_id) INTO v_id FROM (
        SELECT a.entity_id FROM entity_aliases a WHERE name_key(a.alias_text) = v_key
        UNION ALL
        SELECT e.entity_id FROM entities e WHERE name_key(e.entity_name) = v_key);

    IF v_id IS NULL AND p_acronym IS NOT NULL AND p_type = 'ORGANISATION' THEN
        SELECT MIN(a.entity_id) INTO v_id
          FROM entity_aliases a JOIN entities e ON e.entity_id = a.entity_id
         WHERE name_key(a.alias_text) = name_key(p_acronym) AND e.entity_type = 'ORGANISATION';
    END IF;

    IF v_id IS NULL AND p_create = 'Y' THEN
        BEGIN
            INSERT INTO entities (entity_name, entity_type, description)
            VALUES (v_text, p_type, 'Detected in retrieved evidence')
            RETURNING entity_id INTO v_id;
        EXCEPTION
            WHEN DUP_VAL_ON_INDEX THEN
                SELECT MIN(entity_id) INTO v_id FROM entities
                 WHERE entity_name = v_text AND entity_type = p_type;
        END;
    END IF;

    -- Remember the surface form as an alias (alias text is globally unique)
    IF v_id IS NOT NULL AND p_create = 'Y' THEN
        MERGE INTO entity_aliases a
        USING (SELECT v_text AS alias_text FROM dual) src
           ON (a.alias_text = src.alias_text)
         WHEN NOT MATCHED THEN INSERT (entity_id, alias_text) VALUES (v_id, src.alias_text);
    END IF;
    RETURN v_id;
END resolve_entity;
