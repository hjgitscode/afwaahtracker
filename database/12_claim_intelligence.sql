-- Normalised name key used to match aliases: honorifics, punctuation, spaces
-- and case are ignored ("Dr. G. V. Selvam" = "GV Selvam" = GVSELVAM).
-- DETERMINISTIC so it can back a function-based index.
CREATE OR REPLACE FUNCTION name_key (p_text IN VARCHAR2)
RETURN VARCHAR2 DETERMINISTIC
IS
    v VARCHAR2(400) := UPPER(TRIM(SUBSTR(p_text, 1, 400)));
BEGIN
    IF v IS NULL THEN
        RETURN NULL;
    END IF;
    FOR i IN 1 .. 3 LOOP
        v := REGEXP_REPLACE(v, '^(DR|PROF|PROFESSOR|MR|MRS|MS|MISS|SHRI|SRI|SMT|SIR|HON|ER)\.?\s+', '');
    END LOOP;
    RETURN SUBSTR(REGEXP_REPLACE(v, '[^A-Z0-9]', ''), 1, 200);
END name_key;
