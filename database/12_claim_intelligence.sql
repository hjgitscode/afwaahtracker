--------------------------------------------------------------------------------
-- Demonstration data: structured values that are already curated are carried
-- over (nothing is invented for live data).
--   * each DEMO variant's curated wording becomes its SOURCE_EVIDENCE row
--     (extraction_method CURATED) and the variant points to it
--   * a DEMO claim gets a proposition only where actor + action of its
--     best-matching variant map onto a known predicate
-- The demo Mutation Ledger is unchanged (relation fields stay NULL).
--------------------------------------------------------------------------------
DECLARE
    v_eid NUMBER;
BEGIN
    FOR v IN (SELECT cv.variant_id, cv.source_id, cv.variant_text
                FROM claim_variants cv
                JOIN sources s ON s.source_id = cv.source_id
               WHERE s.origin_type = 'DEMO' AND cv.evidence_id IS NULL)
    LOOP
        v_eid := record_evidence(v.source_id, NULL, v.variant_text, 0, 100, 'DIRECT_STATEMENT', 'CURATED');
        UPDATE claim_variants SET evidence_id = v_eid WHERE variant_id = v.variant_id;
    END LOOP;

    FOR c IN (SELECT claim_id, actor, predicate, obj
                FROM (SELECT cl.claim_id, v.actor,
                             CASE v.action WHEN 'Visit' THEN 'VISITED' WHEN 'Perform' THEN 'PERFORMED_AT'
                                           WHEN 'Launch' THEN 'LAUNCHED' WHEN 'Cancel' THEN 'CANCELLED'
                                           WHEN 'Postpone' THEN 'POSTPONED' WHEN 'Announce' THEN 'ANNOUNCED'
                                           WHEN 'Ban' THEN 'BANNED' WHEN 'Release' THEN 'RELEASED'
                                           WHEN 'Acquire' THEN 'ACQUIRED' WHEN 'Approve' THEN 'APPROVED'
                                           WHEN 'Reject' THEN 'REJECTED' END AS predicate,
                             COALESCE(v.target_object, v.event_name, v.location_name) AS obj,
                             ROW_NUMBER() OVER (PARTITION BY cl.claim_id
                                                ORDER BY wording_similarity(v.variant_text, cl.canonical_claim) DESC,
                                                         v.variant_id) AS rn
                        FROM claims cl
                        JOIN claim_variants v ON v.claim_id = cl.claim_id
                       WHERE cl.claim_origin = 'DEMO'
                         AND NOT EXISTS (SELECT 1 FROM claim_propositions p WHERE p.claim_id = cl.claim_id))
               WHERE rn = 1 AND actor IS NOT NULL AND predicate IS NOT NULL AND obj IS NOT NULL)
    LOOP
        DECLARE
            v_subj NUMBER := resolve_entity(c.actor, 'PERSON', 'N');
            v_skey VARCHAR2(210) := NVL2(v_subj, 'E' || v_subj, name_key(c.actor));
            v_okey VARCHAR2(210) := name_key(c.obj);
            v_sig  VARCHAR2(400) := v_skey || '|' || c.predicate || '|' || v_okey || '|-|CURRENT';
        BEGIN
            INSERT INTO claim_propositions
                (claim_id, claim_type, subject_entity_id, subject_text, subject_key, predicate_code,
                 object_text, object_key, normalized_signature, proposition_origin)
            SELECT c.claim_id, 'EVENT_ACTION', v_subj, c.actor, v_skey, c.predicate,
                   c.obj, v_okey, v_sig, 'CURATED_DEMO'
              FROM dual
             WHERE NOT EXISTS (SELECT 1 FROM claim_propositions WHERE normalized_signature = v_sig);
        END;
    END LOOP;
    COMMIT;
END;
/

