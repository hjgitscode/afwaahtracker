--------------------------------------------------------------------------------
-- VW_CLAIM_VARIATION: every structured version of a claim with, per claim
-- family, whether each tracked dimension takes more than one value. Values
-- are normalised first (case, spacing, names by NAME_KEY, relation objects by
-- their proposition key), so cosmetic differences are not variation.
-- No order, no parent, no copying is implied.
--------------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_claim_variation AS
SELECT v.claim_id,
       v.variant_id,
       v.source_id,
       s.publisher,
       s.published_at,
       v.variant_text,
       NVL(v.certainty, 'UNSTATED')                                         AS certainty,
       v.claimed_date,
       v.quantity_value,
       v.location_name,
       v.event_name,
       v.attribution,
       v.relation_subject,
       v.relation_predicate,
       v.relation_object,
       v.relation_qualifier,
       COUNT(*) OVER (PARTITION BY v.claim_id)                              AS variant_count,
       CASE WHEN COUNT(DISTINCT NVL(v.certainty, 'UNSTATED')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS certainty_varies,
       CASE WHEN COUNT(DISTINCT NVL(LOWER(TRIM(v.claimed_date)), '~')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS date_varies,
       CASE WHEN COUNT(DISTINCT NVL(LOWER(REGEXP_REPLACE(v.quantity_value, '\s+', ' ')), '~')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS quantity_varies,
       CASE WHEN COUNT(DISTINCT NVL(name_key(v.location_name), '~')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS location_varies,
       CASE WHEN COUNT(DISTINCT NVL(name_key(v.event_name), '~')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS event_varies,
       CASE WHEN COUNT(DISTINCT NVL(name_key(v.attribution), '~')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS attribution_varies,
       CASE WHEN COUNT(DISTINCT NVL(v.relation_object_key, NVL(name_key(v.relation_object), '~'))) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS object_varies,
       CASE WHEN COUNT(DISTINCT NVL(name_key(v.relation_qualifier), '~')) OVER (PARTITION BY v.claim_id) > 1
            THEN 'Y' ELSE 'N' END                                            AS qualifier_varies
  FROM claim_variants v
  JOIN sources s ON s.source_id = v.source_id;

--------------------------------------------------------------------------------
-- VW_CLAIM_NOVELTY_DIAGNOSTICS (+ analysis coverage): every count Oracle
-- holds for one claim family. A zero here is a zero in the stored relations.
--------------------------------------------------------------------------------
CREATE OR REPLACE VIEW vw_claim_novelty_diagnostics AS
SELECT c.claim_id,
       c.status,
       c.merged_into_claim_id,
       CASE WHEN p.claim_id IS NULL THEN 'N' ELSE 'Y' END                         AS has_proposition,
       p.normalized_signature,
       (SELECT COUNT(DISTINCT v.source_id) FROM claim_variants v WHERE v.claim_id = c.claim_id) AS source_count,
       (SELECT COUNT(DISTINCT v.source_id) FROM claim_variants v
         WHERE v.claim_id = c.claim_id
           AND EXISTS (SELECT 1 FROM source_evidence e WHERE e.source_id = v.source_id))        AS readable_source_count,
       (SELECT COUNT(DISTINCT v.evidence_id) FROM claim_variants v WHERE v.claim_id = c.claim_id) AS evidence_count,
       (SELECT COUNT(*)
          FROM source_evidence e
         WHERE e.source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS stored_sentence_count,
       (SELECT COUNT(*) FROM claim_variants v WHERE v.claim_id = c.claim_id AND v.evidence_id IS NOT NULL) AS variants_with_evidence,
       (SELECT COUNT(*) FROM claim_variants v WHERE v.claim_id = c.claim_id)                 AS variant_count,
       (SELECT COUNT(*) FROM claim_variants v
         WHERE v.claim_id = c.claim_id
           AND (v.relation_predicate IS NOT NULL OR v.action IS NOT NULL))                    AS structured_variant_count,
       (SELECT COUNT(*) FROM claim_variants v JOIN sources s ON s.source_id = v.source_id
         WHERE v.claim_id = c.claim_id AND s.published_at IS NOT NULL)                        AS dated_variant_count,
       (SELECT COUNT(*) FROM claim_variants v
         WHERE v.claim_id = c.claim_id AND v.parent_variant_id IS NOT NULL)                  AS variants_with_parent,
       (SELECT COUNT(*) FROM claim_variants v
          JOIN claim_variants pv ON pv.variant_id = v.parent_variant_id
         WHERE v.claim_id = c.claim_id AND pv.claim_id = c.claim_id)                          AS claim_lineage_edges,
       (SELECT COUNT(*) FROM claim_variants v
         WHERE v.claim_id = c.claim_id
           AND v.lineage_basis IN ('EXPLICIT_REFERENCE','ATTRIBUTION_REFERENCE'))             AS referenced_parent_count,
       (SELECT COUNT(*) FROM claim_mutations m WHERE m.claim_id = c.claim_id)                AS mutation_count,
       (SELECT COUNT(DISTINCT m.child_variant_id) FROM claim_mutations m WHERE m.claim_id = c.claim_id) AS transitions_with_change,
       (SELECT COUNT(*) FROM vw_claim_variation x
         WHERE x.claim_id = c.claim_id AND x.variant_id = (SELECT MIN(y.variant_id) FROM claim_variants y WHERE y.claim_id = c.claim_id)
           AND 'Y' IN (x.certainty_varies, x.date_varies, x.quantity_varies, x.location_varies,
                       x.event_varies, x.attribution_varies, x.object_varies, x.qualifier_varies)) AS has_variation,
       (SELECT COUNT(*) FROM source_references r
         WHERE r.from_source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS source_reference_count,
       (SELECT COUNT(*) FROM source_references r
         WHERE r.from_source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)
           AND r.to_source_id   IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS in_family_reference_count,
       (SELECT COUNT(*) FROM source_attributions a
         WHERE a.source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS stated_attribution_count,
       (SELECT COUNT(DISTINCT a.source_id) FROM source_attributions a
         WHERE a.source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS sources_with_stated_credit,
       (SELECT COUNT(*) FROM source_attributions a
         WHERE a.resolution_status = 'RESOLVED'
           AND a.source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS resolved_attribution_count,
       (SELECT COUNT(*) FROM source_attributions a
         WHERE a.resolution_status = 'UNRESOLVED'
           AND a.source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS unresolved_attribution_count,
       (SELECT COUNT(DISTINCT v.source_id) FROM claim_variants v JOIN sources s ON s.source_id = v.source_id
         WHERE v.claim_id = c.claim_id AND s.derived_from_source_id IS NOT NULL)              AS sources_with_known_upstream,
       (SELECT COUNT(*) FROM (SELECT r.from_source_id, r.to_source_id FROM source_references r
                              UNION
                              SELECT s.source_id, s.derived_from_source_id FROM sources s
                               WHERE s.derived_from_source_id IS NOT NULL) e
         WHERE e.from_source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = c.claim_id)) AS source_lineage_edges,
       calculate_echo_ratio(c.claim_id)                                                       AS known_echo_ratio,
       (SELECT COUNT(DISTINCT v.source_id) FROM claim_variants v JOIN sources s ON s.source_id = v.source_id
         WHERE v.claim_id = c.claim_id AND s.published_at IS NOT NULL)                        AS dated_source_count
  FROM claims c
  LEFT JOIN claim_propositions p ON p.claim_id = c.claim_id;
