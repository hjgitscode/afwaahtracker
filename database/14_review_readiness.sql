-- Safe on an existing database and safe to run again (adds / widens /
-- replaces only; no data is deleted). The strict rules of Known Echo Ratio,
-- Claim Lineage, Source Lineage and the Mutation Ledger are NOT changed.
--
--   CLAIM_PROPOSITIONS predicate CHECK widened to the action registry
--                            (IMPOSED, RAISED, CUT, ARRESTED, WON, MET ...)
--   SOURCE_ATTRIBUTIONS      STATED provenance: every explicit credit a page
--                            makes ("according to Reuters", "via PTI"), kept
--                            even when the credited article was not retrieved.
--                            RESOLVED only when it points to a stored source in
--                            the same claim family (then SOURCE_REFERENCES has
--                            the ATTRIBUTION edge, as before). An UNRESOLVED
--                            credit never creates an edge and never changes
--                            the Known Echo Ratio.
--   RECORD_STATED_ATTRIBUTION / RESOLVE_CLAIM_ATTRIBUTIONS
--   FINALISE_CLAIM_LINEAGE   now first re-tries unresolved credits of the claim
--   VW_CLAIM_VARIATION       how the retrieved versions of a claim differ,
--                            WITHOUT order or parentage (analytic COUNT DISTINCT
--                            per claim decides which dimensions vary)
--   VW_CLAIM_NOVELTY_DIAGNOSTICS  + analysis coverage counts
--------------------------------------------------------------------------------
