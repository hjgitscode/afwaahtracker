--------------------------------------------------------------------------------
-- RECORD_STATED_ATTRIBUTION: keep the credit a page states, then try to
-- resolve it with the existing strict rule (RECORD_ATTRIBUTION_REFERENCE:
-- a stored source of that publisher in the same claim family). Returns the
-- number of NEW SOURCE_REFERENCES rows (0 or 1).
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION record_stated_attribution (
    p_source_id IN NUMBER,
    p_publisher IN VARCHAR2,
    p_phrase    IN VARCHAR2 DEFAULT NULL,
    p_run_id    IN NUMBER   DEFAULT NULL
) RETURN NUMBER
IS
    v_key    VARCHAR2(200) := name_key(p_publisher);
    v_new    NUMBER := 0;
    v_target NUMBER;
BEGIN
    IF p_source_id IS NULL OR v_key IS NULL OR LENGTH(v_key) < 2 THEN
        RETURN 0;
    END IF;

    MERGE INTO source_attributions a
    USING (SELECT p_source_id AS source_id, v_key AS publisher_key FROM dual) x
       ON (a.source_id = x.source_id AND a.publisher_key = x.publisher_key)
     WHEN NOT MATCHED THEN
          INSERT (source_id, search_run_id, publisher_text, publisher_key, attribution_phrase, resolution_status)
          VALUES (p_source_id, p_run_id, SUBSTR(TRIM(p_publisher), 1, 200), v_key, SUBSTR(p_phrase, 1, 400), 'UNRESOLVED');

    v_new := NVL(record_attribution_reference(p_source_id, p_publisher), 0);

    SELECT MIN(r.to_source_id) KEEP (DENSE_RANK FIRST ORDER BY t.published_at NULLS LAST, t.source_id)
      INTO v_target
      FROM source_references r
      JOIN sources t ON t.source_id = r.to_source_id
     WHERE r.from_source_id = p_source_id
       AND r.reference_type = 'ATTRIBUTION'
       AND publisher_matches(t.publisher, p_publisher) = 1;

    IF v_target IS NOT NULL THEN
        UPDATE source_attributions
           SET resolved_source_id = v_target,
               resolution_status  = 'RESOLVED',
               resolution_method  = 'STORED_PUBLISHER_IN_FAMILY',
               updated_at         = SYSTIMESTAMP
         WHERE source_id = p_source_id AND publisher_key = v_key
           AND (resolution_status <> 'RESOLVED' OR resolved_source_id <> v_target);
    END IF;
    RETURN v_new;
END record_stated_attribution;
/

--------------------------------------------------------------------------------
-- RESOLVE_CLAIM_ATTRIBUTIONS: a credited publisher's article may join the
-- family after the citing page; re-try every unresolved credit of the claim.
--------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION resolve_claim_attributions (p_claim_id IN NUMBER)
RETURN NUMBER
IS
    v_added NUMBER := 0;
BEGIN
    FOR a IN (SELECT a.source_id, a.publisher_text, a.attribution_phrase, a.search_run_id
                FROM source_attributions a
               WHERE a.resolution_status = 'UNRESOLVED'
                 AND a.source_id IN (SELECT v.source_id FROM claim_variants v WHERE v.claim_id = p_claim_id))
    LOOP
        v_added := v_added + record_stated_attribution(a.source_id, a.publisher_text, a.attribution_phrase, a.search_run_id);
    END LOOP;
    RETURN v_added;
END resolve_claim_attributions;
/

--------------------------------------------------------------------------------
-- FINALISE_CLAIM_LINEAGE: stated credits -> known upstream sources -> wording
-- parents -> Mutation Ledger (the last three exactly as in migration 13)
--------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE finalise_claim_lineage (p_claim_id IN NUMBER)
IS
    v_n NUMBER;
BEGIN
    v_n := resolve_claim_attributions(p_claim_id);
    v_n := refresh_claim_provenance(p_claim_id);
    relink_claim_lineage(p_claim_id);
    rebuild_claim_mutations(p_claim_id);
END finalise_claim_lineage;
